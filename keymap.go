var scanCodeByName = map[string]uint32{}
var vkCodeByName = map[string]uint32{}

func init() {
	for c, n := range evdevNameByCode {
		evdevCodeByName[n] = c
	}
	for c, n := range scanNameByCode {
		if _, ok := scanCodeByName[n]; !ok {
			scanCodeByName[n] = c
		}
	}
	for c, n := range vkNameByCode {
		if _, ok := vkCodeByName[n]; !ok {
			vkCodeByName[n] = c
		}
	}
}

func normalizeKeyInput(s string) (string, bool) {
	s = strings.TrimSpace(s)
	if s == "" {
		return "", false
	}
	up := strings.ToUpper(s)
	if _, ok := evdevCodeByName[up]; ok {
		return up, true
	}
	if len(s) == 1 && (s[0] >= 'A' && s[0] <= 'Z' || s[0] >= 'a' && s[0] <= 'z') {
		name := "KEY_" + up
		if _, ok := evdevCodeByName[name]; ok {
			return name, true
		}
		return "", false
	}
	base := 10
	t := up
	if strings.HasPrefix(up, "0X") {
		base = 16
		t = up[2:]
	}
	v, err := strconv.ParseUint(t, base, 16)
	if err != nil || v > keyMaxNative {
		return "", false
	}
	if n, ok := evdevNameByCode[uint16(v)]; ok {
		return n, true
	}
	return "", false
}